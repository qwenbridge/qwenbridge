package io.qwenbridge.core.threat;

/**
 * Where a text came from, which decides how much it may influence the system (QB-067).
 *
 * <p>Only operator-authored instructions (prompt templates, policies) are trusted, and they never
 * pass through threat detection because they are not input. Everything else is data: it can be
 * searched, ranked or summarized, but an instruction inside it is never obeyed. Detection adds a
 * signal; the boundary itself does not depend on detection succeeding.
 */
public enum TrustZone {
  /** Text the end user sent (query, conversation turn). */
  USER_INPUT,
  /** Content returned by a retrieval connector (documents, product data, logs). */
  RETRIEVED_CONTENT,
  /** Output of a tool, plugin or connector call. */
  TOOL_OUTPUT,
  /** Text generated by a model, before it is shown or acted on. */
  MODEL_OUTPUT
}
