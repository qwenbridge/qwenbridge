#!/usr/bin/env python3
"""Keep k6's visible cases identical to the live JUnit reference corpus."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'qwenbridge-server/src/test/resources/commerce/language-cases.json'
target = root / 'scripts/performance/commerce-corpus.js'
cases = json.loads(source.read_text())
assert len({row['id'] for row in cases}) == len(cases)
content = '// Generated by scripts/verification/generate-language-corpus.py; edit the JSON source.\n'
content += 'export const commerceCases = ' + json.dumps(cases, ensure_ascii=False, indent=2) + ';\n'
content += 'export const commerceQueries = commerceCases.map(c => c.query);\n'
if '--write' in sys.argv:
    target.write_text(content)
else:
    assert target.read_text() == content, 'Run python3 scripts/verification/generate-language-corpus.py --write'
print(f'PASS: {len(cases)} commerce cases shared by JUnit and k6')
